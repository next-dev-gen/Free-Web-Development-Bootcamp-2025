// Declare two variables 'a' and 'b' using let
let a = 30;
let b = 60;

// Compare the values of 'a' and 'b' using an if-else statement
if (a > b) {
    // This block runs if 'a' is greater than 'b'
    console.log("A is greater than B");
} else {
    // This block runs if 'a' is not greater than 'b' (meaning 'b' is greater or equal)
    console.log("B is greater than A");
}


// Declare a constant variable 'mark' to store a student's score
const mark = 70;

// Use if-else if-else statements to determine the grade based on the mark
if (mark >= 80) {
    // Runs if mark is 80 or above
    console.log("You have got A+ grade");
} else if (mark >= 70) {
    // Runs if mark is between 70 and 79
    console.log("You have got A grade");
} else if (mark >= 60) {
    // Runs if mark is between 60 and 69
    console.log("You have got B grade");
} else {
    // Runs if mark is below 60
    console.log("You have failed");
}


