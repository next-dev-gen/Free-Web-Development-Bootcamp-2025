// Declare a variable using 'var' keyword and assign the value 10
var a = 10;

// Print the value of variable 'a' to the console
console.log(a); // Output: 10


// Declare another variable using 'var' keyword and assign a string value
var b = "Hello Variable";

// Print the value of variable 'b' to the console
console.log(b); // Output: Hello Variable


// Declare a variable using 'let' keyword which allows reassignment
let c = 30;

// Update the value of 'c' by adding 10 to its existing value
c = c + 10;

// Print the updated value of 'c' to the console
console.log(c); // Output: 40


// Declare a constant variable using 'const' keyword which cannot be reassigned
const d = false;

// Print the value of the constant 'd' to the console
console.log(d); // Output: false


