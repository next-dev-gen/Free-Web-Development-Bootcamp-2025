// -----------------------------------------------

// ✅ Using a FOR loop
console.log("For Loop:");
for (let index = 1; index <= 100; index++) {
    // Prints the number and the word "Allah" on each line
    console.log(index + ": " + "Allah");
}


// ✅ Using a WHILE loop
console.log("While Loop:");
let index = 1; // Initialize counter variable
while (index <= 100) {
    // Prints the number and the word "Allah" on each line
    console.log(index + ": " + "Allah");
    index++; // Increment counter after each loop
}


